"""
Report Routes Blueprint
Handles export and download of comprehensive scientific analysis reports.
Generates structured 12-point scientific significance and trend reports in Markdown or JSON format.
"""

from flask import Blueprint, jsonify, request, Response
from backend.services.data_loader import DataLoaderService

report_bp = Blueprint("report", __name__)
data_loader = DataLoaderService()


def generate_markdown_report(report_id: str, analysis: dict) -> str:
    """Formats analysis JSON into 12-point scientific Markdown report."""
    loc = analysis.get("location", {})
    loc_name = loc.get("name", "Unknown Location")
    loc_type = loc.get("type", "region")
    period = analysis.get("period", {})
    start = period.get("start", "2000")
    end = period.get("end", "2025")
    results = analysis.get("results", [])

    lines = [
        f"# TerraScope Scientific Report: Earth System Trends ({loc_name})",
        "",
        f"> **Report Identifier**: `{report_id}`  ",
        f"> **Generated By**: TerraScope (India Edition)  ",
        f"> **Temporal Window**: {start} – {end}  ",
        f"> **Target Area**: {loc_name} ({loc_type.capitalize()})  ",
        "",
        "---",
        "",
        "## 1. Executive Summary",
        ""
    ]

    for r in results:
        lines.append(f"- **{r.get('friendly_name', r.get('variable'))}**: {r.get('summary', 'Analysis completed.')}")

    lines.extend([
        "",
        "## 2. Spatial Scope & Geographic Definition",
        f"- **Location**: {loc_name}",
        f"- **Administrative Type**: {loc_type.capitalize()}",
        f"- **Centroid / Coordinates**: {loc.get('centroid') or loc.get('coordinates') or 'N/A'}",
        "",
        "## 3. Monitored Earth System Variables & Data Sources",
        "| Variable | Parameter Code | Unit | Primary Remote Sensing Source |",
        "|---|---|---|---|"
    ])

    for r in results:
        lines.append(f"| {r.get('friendly_name', r.get('variable'))} | {r.get('variable', '').upper()} | {r.get('unit', '')} | {r.get('source', 'NASA POWER')} |")

    lines.extend([
        "",
        "## 4. Observational Period & Temporal Sampling",
        f"- **Start Year**: {start}",
        f"- **End Year**: {end}",
        f"- **Latest Validated Record**: {period.get('latest_available', 'Recent')}",
        "",
        "## 5. Descriptive Baseline Statistics",
        "| Variable | Sample Size ($N$) | Mean | Min | Max |",
        "|---|---|---|---|---|"
    ])

    for r in results:
        lines.append(f"| {r.get('friendly_name', r.get('variable'))} | {r.get('n_observations', len(r.get('series', [])))} | {r.get('mean', 'N/A')} | {r.get('min', 'N/A')} | {r.get('max', 'N/A')} |")

    lines.extend([
        "",
        "## 6. Mann-Kendall Non-Parametric Trend Evaluation",
        "| Variable | Test Direction | $p$-value | Significant ($p < 0.05$)? |",
        "|---|---|---|---|"
    ])

    for r in results:
        trend = r.get("trend", {})
        sig = "Yes" if trend.get("significant") else "No"
        p_val = trend.get("p_value", "N/A")
        if isinstance(p_val, float):
            p_val = f"{p_val:.4f}"
        lines.append(f"| {r.get('friendly_name', r.get('variable'))} | {trend.get('direction', 'N/A')} | {p_val} | {sig} |")

    lines.extend([
        "",
        "## 7. Sen's Slope Rate of Change & 95% Confidence Bounds",
        "| Variable | Rate per Decade | 95% CI Lower | 95% CI Upper | Symbol |",
        "|---|---|---|---|---|"
    ])

    for r in results:
        trend = r.get("trend", {})
        ci = trend.get("confidence_interval_95", ["N/A", "N/A"])
        lines.append(f"| {r.get('friendly_name', r.get('variable'))} | {trend.get('slope_per_decade', 'N/A')} {r.get('unit')}/dec | {ci[0]} | {ci[1]} | {trend.get('symbol', '=')} |")

    lines.extend([
        "",
        "## 8. Five-Tier Qualitative Change Classification",
        "| Variable | Classification Category | Symbol |",
        "|---|---|---|"
    ])

    for r in results:
        trend = r.get("trend", {})
        lines.append(f"| {r.get('friendly_name', r.get('variable'))} | {trend.get('class', 'no_clear_change').replace('_', ' ').capitalize()} | `{trend.get('symbol', '=')}` |")

    lines.extend([
        "",
        "## 9. Plain-Language Narrative Interpretation",
        ""
    ])

    for r in results:
        lines.append(f"> \"{r.get('summary', '')}\"")
        lines.append("")

    lines.extend([
        "## 10. Observational Limitations & Known Biases",
        ""
    ])

    for r in results:
        limits = r.get("limitations", [])
        for lim in limits:
            lines.append(f"- {lim}")

    lines.extend([
        "",
        "## 11. Environmental Hypotheses & Regional Context",
        ""
    ])

    for r in results:
        hyps = r.get("hypotheses", [])
        for h in hyps:
            lines.append(f"- {h}")

    lines.extend([
        "",
        "## 12. Attribution, Reproducibility & Citations",
        "- **Data Provider**: NASA Prediction of Worldwide Energy Resources (POWER) Project.",
        "- **Statistical Framework**: Mann-Kendall Test (Mann 1945, Kendall 1975) & Sen's Slope Estimator (Sen 1968).",
        "- **Platform**: TerraScope Earth System Trend Detective (India Edition)."
    ])

    return "\n".join(lines)


@report_bp.route("/report/<report_id>", methods=["GET"])
def get_report(report_id):
    """
    Downloads or views a formatted statistical significance and trend report.
    Query parameters:
        format: "markdown" (default) or "json"
    """
    fmt = request.args.get("format", "markdown").lower()

    # Retrieve cached analysis
    analysis = data_loader.get_cache(f"report_{report_id}")
    if not analysis:
        analysis = data_loader.get_cache(report_id)

    # Fallback to sample data for demo/testing report IDs
    if not analysis and report_id.lower() in ("sample", "kerala", "default"):
        analysis = data_loader.load_sample("kerala_temperature_sample.json")

    if not analysis:
        return jsonify({
            "status": "not_found",
            "message": f"Report with identifier '{report_id}' was not found.",
            "report_id": report_id
        }), 404

    if fmt == "json":
        return jsonify({
            "status": "success",
            "report_id": report_id,
            "format": "json",
            "data": analysis
        }), 200

    # Markdown format
    md_content = generate_markdown_report(report_id, analysis)
    if request.headers.get("Accept") == "text/markdown":
        return Response(md_content, mimetype="text/markdown")

    return jsonify({
        "status": "success",
        "report_id": report_id,
        "format": "markdown",
        "content": md_content
    }), 200
